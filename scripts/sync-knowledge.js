#!/usr/bin/env node
'use strict';

/**
 * Syncs the learning notes into the skill as local knowledge.
 *
 *   notes/<NN-phase>/*.md  ──copy (flattened)──▶  skills/frontend-system-design/references/knowledge/*.md
 *   README roadmap + note metadata ──generate──▶ knowledge/INDEX.md + knowledge/index.json
 *
 * Notes live in one folder per roadmap phase (notes/01-web-fundamentals/, …). The skill's
 * knowledge/ stays flat, so links between notes in different phase folders
 * (../02-rendering-and-architecture/x.md) are rewritten to ./x.md when copied.
 *
 * The notes serve two audiences:
 *   - learners read them (or use /fsd:learn);
 *   - builders get designs whose decisions cite them (via INDEX.md / index.json).
 *
 * Usage:
 *   node scripts/sync-knowledge.js           # write
 *   node scripts/sync-knowledge.js --check   # exit 1 if the committed copy is stale (CI)
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const NOTES = path.join(ROOT, 'notes');
const OUT = path.join(ROOT, 'skills', 'frontend-system-design', 'references', 'knowledge');
const REPO = 'https://github.com/Muzammil8989/frontend-system-design';
const HEADER = '<!-- Generated by scripts/sync-knowledge.js from notes/ and README.md — do not edit here. -->';

// Roadmap category → the design decisions that topic informs (used for planned topics
// and as a fallback when a note has no "Informs:" line).
const CATEGORY_DECISIONS = {
  'Browser Internals': 'rendering cost, main-thread budget, DOM update strategy',
  Networking: 'API protocol, latency, connection reuse, CDN, CORS',
  'Browser APIs': 'background work, observers, offloading the main thread',
  Caching: 'HTTP caching, CDN, service worker strategy',
  'Rendering Patterns': 'rendering strategy per route (CSR/SSR/SSG/ISR/streaming/islands/edge)',
  Architecture: 'app structure, team boundaries, design system, module boundaries',
  'Build Tools': 'bundling, code splitting, build pipeline',
  'State Management': 'client vs server state, store choice',
  'Data Fetching': 'caching, pagination, optimistic UI, real-time, offline sync',
  'Performance Metrics': 'Core Web Vitals targets, budgets, auditing',
  'Loading Performance': 'bundle size, images, fonts, prefetching',
  'Runtime Performance': 'INP, virtualization, memoization, workers, memory',
  'Design System': 'tokens, component APIs, documentation',
  'Component Patterns': 'component API design, composition, reuse',
  Styling: 'CSS architecture, responsive design, theming',
  Accessibility: 'WCAG 2.2 AA, keyboard, screen readers, testing',
  Internationalization: 'i18n architecture, RTL, formatting',
  'Frontend Security': 'XSS, CSP, CSRF, auth flows, token storage, supply chain',
  Testing: 'test strategy, tooling, CI quality gates',
  'Error Handling': 'error boundaries, error tracking',
  Monitoring: 'RUM, synthetic monitoring, logging',
  Analytics: 'feature flags, experiments, analytics architecture',
  Advanced: 'PWA, WASM, Web Components, BFF auth, SEO, CI/CD, CDN, monorepo tooling',
};
const CASE_PHASE = 11; // "System Design Cases": starting patterns for builders' problems

const toPosix = (s) => s.replace(/\r\n/g, '\n');
const flattenLinks = (s) => s.replace(/\]\(\.\.\/[a-z0-9-]+\/([a-z0-9-]+\.md)/g, '](./$1');

/** Every note as { slug, dir, abs }, from notes/<phase-folder>/*.md (and notes/*.md, if any). */
function listNotes() {
  const out = [];
  const add = (dir) => {
    for (const f of fs.readdirSync(path.join(NOTES, dir))) {
      if (f.endsWith('.md') && !f.startsWith('_') && f !== 'README.md') {
        out.push({ slug: f.replace(/\.md$/, ''), dir, abs: path.join(NOTES, dir, f) });
      }
    }
  };
  add('');
  for (const d of fs.readdirSync(NOTES, { withFileTypes: true })) if (d.isDirectory()) add(d.name);
  return out.sort((a, b) => a.slug.localeCompare(b.slug));
}

function noteMeta(file) {
  const text = toPosix(fs.readFileSync(file, 'utf8'));
  const lines = text.split('\n');
  const get = (key) => {
    const m = text.match(new RegExp(`\\*\\*${key}:\\*\\*\\s*([^\\n·]+)`));
    return m ? m[1].trim() : '';
  };
  // One-line takeaway: the blockquote inside the ELI5 section
  let takeaway = '';
  const start = lines.findIndex((l) => /^## ELI5/.test(l));
  if (start !== -1) {
    const quote = [];
    for (let i = start + 1; i < lines.length && !/^## /.test(lines[i]); i++) {
      if (/^> /.test(lines[i])) quote.push(lines[i].slice(2));
      else if (quote.length) break;
    }
    takeaway = quote
      .map((q) => q.replace(/\*\*/g, '').trim())
      .reduce((acc, q) => (acc ? `${acc}${/[.!?:]$/.test(acc) ? '' : '.'} ${q}` : q), '')
      .replace(/^One-line takeaway:\s*/i, '')
      .trim();
  }
  return {
    title: (lines.find((l) => /^# /.test(l)) || '').slice(2).trim(),
    subTopic: get('Sub-Topic'),
    level: get('Level'),
    informs: get('Informs'),
    takeaway,
  };
}

function roadmap() {
  const lines = toPosix(fs.readFileSync(path.join(ROOT, 'README.md'), 'utf8')).split('\n');
  const topics = [];
  let phase = null;
  let phaseName = '';
  for (const line of lines) {
    const ph = line.match(/^## Phase (\d+) — (.+)$/);
    if (ph) {
      phase = Number(ph[1]);
      phaseName = ph[2].trim();
      continue;
    }
    if (/^## /.test(line)) phase = null;
    if (phase === null) continue;
    const row = line.match(/^\|\s*(\d+)\s*\|\s*(✅|⬜)\s*(.+?)\s*\|\s*(.+?)\s*\|$/);
    if (!row) continue;
    const link = row[3].match(/\[([^\]]+)\]\(\.?\/?notes\/(?:([a-z0-9-]+)\/)?([a-z0-9-]+)\.md\)/);
    topics.push({
      number: Number(row[1]),
      phase,
      phaseName,
      title: link ? link[1] : row[3].trim(),
      slug: link ? link[3] : null,
      dir: link ? link[2] || '' : null,
      written: row[2] === '✅' && !!link,
      category: row[4].trim(),
    });
  }
  return topics;
}

/**
 * H2 sections of a note as { name, start, end } (1-based, inclusive), skipping headings inside code fences.
 * `offset` shifts the numbers to where the note's lines land in the generated copy.
 */
function sectionMap(body, offset) {
  const lines = body.split('\n');
  const heads = [];
  let fence = null;
  lines.forEach((line, i) => {
    const f = line.match(/^ {0,3}(`{3,}|~{3,})/);
    if (f) fence = fence ? (f[1][0] === fence[0] && f[1].length >= fence.length ? null : fence) : f[1];
    else if (!fence && /^## /.test(line)) heads.push({ name: line.slice(3).split(' — ')[0].trim(), line: i + 1 });
  });
  return heads.map((h, k) => ({
    name: h.name,
    start: h.line + offset,
    end: (k + 1 < heads.length ? heads[k + 1].line - 1 : lines.length) + offset,
  }));
}

function build() {
  const files = new Map(); // relative path → content
  const meta = {};
  for (const { slug, dir, abs } of listNotes()) {
    if (meta[slug]) throw new Error(`duplicate note slug "${slug}" in notes/${dir}/ and notes/${meta[slug].dir}/`);
    const body = flattenLinks(toPosix(fs.readFileSync(abs, 'utf8'))).trimEnd();
    // Copy = HEADER, section map, blank line, then the note: note line n is line n + 3 of the copy.
    const sections = sectionMap(body, 3);
    const map = `<!-- sections (line ranges in this file): ${sections.map((s) => `${s.name} ${s.start}-${s.end}`).join(' · ')} -->`;
    meta[slug] = { ...noteMeta(abs), dir, sections };
    files.set(`${slug}.md`, `${HEADER}\n${map}\n\n${body}\n`);
  }

  const topics = roadmap().map((t) => {
    const m = t.slug ? meta[t.slug] : null;
    return {
      ...t,
      file: t.written ? `${t.slug}.md` : null,
      informs: (m && m.informs) || CATEGORY_DECISIONS[t.category] || '',
      takeaway: (m && m.takeaway) || '',
      level: (m && m.level) || '',
      url: t.written ? `${REPO}/blob/main/notes/${t.dir ? `${t.dir}/` : ''}${t.slug}.md` : null,
      sections: (m && m.sections) || [],
    };
  });

  // INDEX.md is read on every design and lesson, so it stays compact: one short table per phase.
  // Takeaways, URLs and section maps live in index.json and in each note's header.
  const written = topics.filter((t) => t.written);
  const esc = (s) => String(s).replace(/\|/g, '\\|');
  // First decision areas only, cut at a top-level comma (not inside parentheses); index.json keeps the full list.
  const brief = (s, max = 110) => {
    const parts = [];
    let depth = 0;
    let cur = '';
    for (const ch of s) {
      if (ch === '(') depth++;
      if (ch === ')') depth--;
      if (ch === ',' && depth === 0) { parts.push(cur.trim()); cur = ''; } else cur += ch;
    }
    if (cur.trim()) parts.push(cur.trim());
    let out = parts[0] || '';
    for (const p of parts.slice(1)) {
      if (out.length + p.length + 2 > max) return `${out}, …`;
      out += `, ${p}`;
    }
    return out;
  };
  const phases = [...new Map(topics.map((t) => [t.phase, t.phaseName])).entries()];

  const md = [
    HEADER,
    '',
    '# Knowledge index: Frontend System Design notes',
    '',
    `${written.length} of ${topics.length} roadmap topics are written. Pick the one note that matches the decision or question; don't open several "just in case".`,
    '',
    '**Read notes cheaply.** Line 2 of every note maps its sections to line ranges. Read that line, then only the range you need:',
    '- **Design, advise, audit:** *Key Points Summary* + *Cheat Sheet* (open a *Core Concept* part only if the decision depends on it). Cite it as `knowledge/<file>` + section, and only if you read it.',
    '- **Learn (`/fsd:learn`):** one section at a time, in teaching order: ELI5 → Core Concept → one example → quiz.',
    '- **Planned topic:** teach from `../core/` and `../platforms/`, and say the note is coming.',
    '- **No close match?** `index.json` lists every decision area per note (this table shows the first few).',
    '',
    `Notes: [CC BY 4.0](https://creativecommons.org/licenses/by/4.0/), code snippets MIT. Source: ${REPO}`,
    ...phases.flatMap(([n, name]) => [
      '',
      n === CASE_PHASE ? `## ${n} · ${name}: starting patterns (match the builder's problem to the closest case, then tailor it)` : `## ${n} · ${name}`,
      '',
      '| # | Note | Level | Informs decisions about |',
      '|---|---|---|---|',
      ...topics
        .filter((t) => t.phase === n)
        .map((t) => `| ${t.number} | ${t.written ? `[${esc(t.title)}](./${t.file})` : `${esc(t.title)} *(planned)*`} | ${esc(t.level)} | ${esc(brief(t.informs))} |`),
    ]),
    '',
  ].join('\n');

  files.set('INDEX.md', md);
  files.set('index.json', JSON.stringify({ generated_by: 'scripts/sync-knowledge.js', written: written.length, total: topics.length, topics }, null, 2) + '\n');
  return files;
}

function main() {
  const check = process.argv.includes('--check');
  const files = build();
  const existing = fs.existsSync(OUT) ? fs.readdirSync(OUT) : [];
  const stale = [];

  for (const [name, content] of files) {
    const target = path.join(OUT, name);
    const current = fs.existsSync(target) ? toPosix(fs.readFileSync(target, 'utf8')) : null;
    if (current !== content) stale.push(name);
  }
  const extra = existing.filter((f) => !files.has(f));
  stale.push(...extra.map((f) => `${f} (no longer in notes/)`));

  if (check) {
    if (stale.length) {
      console.log(`✖ knowledge/ is out of sync with notes/: ${stale.join(', ')}\n  Run: npm run sync:knowledge`);
      process.exitCode = 1;
    } else {
      console.log(`✔ knowledge/ in sync (${files.size} files)`);
    }
    return;
  }

  fs.mkdirSync(OUT, { recursive: true });
  for (const f of extra) fs.unlinkSync(path.join(OUT, f));
  for (const [name, content] of files) fs.writeFileSync(path.join(OUT, name), content);
  console.log(`✔ synced ${files.size} files to ${path.relative(ROOT, OUT)}${stale.length ? ` (updated: ${stale.join(', ')})` : ' (no changes)'}`);
}

if (require.main === module) main();
module.exports = { build, roadmap, noteMeta, listNotes, sectionMap };
